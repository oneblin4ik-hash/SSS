/** Короткий код для личной переписки. Юзернейма у человека может не быть,
 *  имя в Telegram может не совпадать с именем из теста, а user_id в личку
 *  не передаётся — без кода Эдуарду придётся переспрашивать «а вы тест
 *  проходили?». Код стабильный: один и тот же человек получит его снова. */
export async function shortCode(userId) {
  const buf = await crypto.subtle.digest(
    "SHA-1",
    new TextEncoder().encode(`serbolin:${userId}`),
  );
  return [...new Uint8Array(buf)]
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("")
    .slice(0, 4)
    .toUpperCase();
}

