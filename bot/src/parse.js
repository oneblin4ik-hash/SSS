/* Разбор ответов «Дня 0».
 *
 * Человек отвечает свободным текстом, и это не ошибка проектирования,
 * а решение: заставить его выбирать время кнопками — значит превратить
 * живой разговор в анкету. Цена решения в том, что разобрать выйдет
 * не всегда.
 *
 * Главное правило: **не досочинять**. Если время не распозналось —
 * в карточке стоит фраза человека целиком, а не придуманное нами число.
 */

/* Время в любом виде, каким его пишут: 7, 7:30, 7.30, 07:05. */
const TIME = /\b(\d{1,2})(?:[:.](\d{2}))?\b/g;

/** Достаёт из фразы до двух моментов времени. Возвращает часы как число
 *  и текст, каким его написал человек. */
export function times(text) {
  const found = [];
  for (const m of String(text || "").matchAll(TIME)) {
    const h = Number(m[1]);
    const min = Number(m[2] || 0);
    if (h > 23 || min > 59) continue;      // «съел 200 грамм» — не время
    found.push({ h, min, raw: m[0] });
    if (found.length === 2) break;
  }
  return found;
}

/**
 * Часы сна между подъёмом и отбоем. Отбой почти всегда вечерний, подъём
 * утренний, поэтому считаем через полночь: лёг в 23, встал в 7 — восемь
 * часов, а не минус шестнадцать.
 *
 * Возвращает null, если распознать не удалось: пусть в карточке лучше
 * не будет строки, чем будет неправда.
 */
export function sleepHours(wake, bed) {
  if (!wake || !bed) return null;
  const w = wake.h * 60 + wake.min;
  const b = bed.h * 60 + bed.min;
  let mins = w - b;
  if (mins <= 0) mins += 24 * 60;
  const hours = mins / 60;
  // Меньше трёх или больше четырнадцати — почти наверняка мы разобрали
  // не то. Молчим, а не показываем ерунду.
  return hours >= 3 && hours <= 14 ? Math.round(hours * 10) / 10 : null;
}

/** Два окна из одной фразы. Режем по запятой, «и», тире — тому, чем люди
 *  на самом деле разделяют. Не вышло на две части — отдаём как есть. */
export function windows(text) {
  const s = String(text || "").trim();
  const parts = s
    .split(/\s*(?:,|;|\sи\s|\/|\sили\s)\s*/i)
    .map((p) => p.trim())
    .filter(Boolean);
  return parts.length === 2 ? parts : null;
}

/** Часы словами: 7.5 → «7 с половиной», 8 → «8». Дробь в тексте про сон
 *  выглядит как отчёт из таблицы, а не как разговор. */
export function hoursWord(h) {
  const whole = Math.floor(h);
  const rest = h - whole;
  if (rest < 0.25) return String(whole);
  if (rest < 0.75) return `${whole} с половиной`;
  return String(whole + 1);
}
