const SLEEP_OK = "Нормально. С таким сном работать проще.";

/**
 * Собирается из четырёх ответов. Числа берём из ответа человека, ничего
 * не досочиняем: если время не разобралось, строка про сон идёт его
 * собственной фразой и без вывода про часы.
 */
export function startCard({ name, gender, sleepLine, windowsLine, hunger, dinner }) {
  return [
    `*${name}, твоя стартовая точка*`,
    ``,
    `*Режим:* ${sleepLine}`,
    `*Твои окна:* ${windowsLine} Тренировки ставим сюда, обеденное время не трогаем.`,
    `*Зона риска:* ${hunger}`,
    `*Вчера вечером:* ${dinner}`,
    ``,
    `Смотри, что произошло. Ты не ${g(gender, "села", "сел")} на диету ` +
    `и не ${g(gender, "пошла", "пошёл")} в зал, а на руках у тебя то, чего ` +
    `не было ни в одном прошлом заходе: конкретное место поломки ` +
    `и конкретные окна под нагрузку.`,
    ``,
    `Это был День 0. Самый простой день моей системы.`,
  ].join("\n");
}

export const sleepVerdict = (hours) => (hours < 7 ? SLEEP_SHORT : SLEEP_OK);
