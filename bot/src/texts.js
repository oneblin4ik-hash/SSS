/* Приписка про врача. Взята из блока .warn в квизе дословно: человек
   читает её на экране диагностики, а через минуту здесь — расхождение
   в формулировке он заметит и решит, что одному из двух текстов верить
   не надо. Требование зафиксировано в спеке, §3. */
export function medicWarning(gender, health = []) {
  const heart = health.includes("heart");
  const diab = health.includes("diab");
  if (!heart && !diab) return null;
  const what = heart && diab ? "сердце и диабет"
             : heart ? "сердце или давление"
             : "диабет";
  return (
    `*Отдельно и без обтекаемых формулировок.* ` +
    `Ты ${g(gender, "отметила", "отметил")} ${what}. ` +
    `Тренер здесь второй, а первый — врач: нужно разрешение на нагрузку ` +
    `и понимание, чего тебе нельзя. Это не отмена плана, а его порядок. ` +
    `Я работал с такими людьми и работаю, но начинаем с бумажки от доктора, ` +
    `а не с приседаний.`
  );
}

