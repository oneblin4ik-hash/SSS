/* Догрев, §5.5. Четыре сообщения закрывают первые двое суток, пока разбор
   ещё свежий. Дальше человек не «горячий лид», а просто читатель, который
   однажды прошёл тест, — пишем редко и по делу, иначе бота отправят в блок
   и адрес сгорит навсегда.
 *
 * Правила хвоста нарушать нельзя:
 *   • не чаще раза в две недели, всего четыре касания, потом тишина;
 *   • «скоро подорожает» — не больше одного раза за всю цепочку. Если бот
 *     полгода пишет «бери, пока не подняли», а цена стоит, человек видит,
 *     что его водят. Здесь этой строки нет вовсе;
 *   • в каждом сообщении хвоста — кнопка отписки, работает с первого раза;
 *   • ответил в чат — цепочка останавливается, дальше живой разговор.
 */
import { g } from "./texts.js";
import { PRICE, BTN_CONTACT } from "./offer.js";

const HOUR = 3600e3;
const DAY = 24 * HOUR;

/* Расписание от момента, когда человек дошёл до конца теста. */
export const SCHEDULE = [
  { kind: "warm_4h", after: 4 * HOUR, tail: false },
  { kind: "warm_24h", after: DAY, tail: false },
  { kind: "warm_3d", after: 3 * DAY, tail: false },
  { kind: "warm_7d", after: 7 * DAY, tail: false },
  { kind: "warm_14d", after: 14 * DAY, tail: true },
  { kind: "warm_30d", after: 30 * DAY, tail: true },
];

/** Текст касания. `d` — строка из day0, может быть пустой: человек мог
 *  бросить диалог, не ответив ни на один вопрос. Тогда подставляем то,
 *  что есть, и не выдумываем. */
export function warmupText(kind, payload, d) {
  const name = payload.n || "";
  const sex = payload.g;
  const zone = d?.hunger_time || null;
  const w1 = d?.window1, w2 = d?.window2;
  const windows = w1 && w2 ? `${w1} и ${w2}` : d?.windows_raw || null;

  switch (kind) {
    case "warm_4h":
      return `${name}, карточка со стартовой точкой у тебя на руках. ` +
        `Что с ней делать дальше — покажет День 1: полный аудит режима, ` +
        `без единого запрета. ${PRICE}.`;

    case "warm_24h": {
      // Без разобранных окон и зоны это сообщение теряет весь смысл —
      // оно целиком построено на «ты знаешь свои». Тогда не пишем вовсе.
      if (!zone || !windows) return null;
      return `Ты знаешь свою зону риска — ${zone}. Знаешь свои окна: ` +
        `${windows}. Через две недели ты про это ${g(sex, "забудешь", "забудешь")}, ` +
        `как ${g(sex, "забывала", "забывал")} прошлые разы, — не из-за лени, ` +
        `а потому что напоминать некому. Курс напоминает каждый день. ` +
        `14 дней, ${PRICE}.`;
    }

    case "warm_3d":
      return `Больше на эту тему писать не буду: либо сейчас, либо в другой ` +
        `раз. Если появятся вопросы — я на месте и отвечаю сам. Разбор ` +
        `бесплатный и без срока: созвон 30 минут.`;

    case "warm_7d": {
      if (!windows) return null;
      return `Прошла неделя. Как дела с теми двумя окнами, ${windows}, — ` +
        `используешь? Если нет, я не удивлён: без структуры они и не должны ` +
        `были заработать. Курс на месте, разбор тоже. Просто напиши.`;
    }

    case "warm_14d":
      return `${name}, две недели назад ты ${g(sex, "прошла", "прошёл")} тест. ` +
        `Вопрос без продажи: ${g(sex, "начала", "начал")} что-то делать ` +
        `или пока думаешь? Если пока думаешь — это нормально, я к тому, ` +
        `что думать можно бесконечно, а День 1 занимает пятнадцать минут.`;

    case "warm_30d": {
      const z = zone ? `Твоя зона риска была ${zone} — она никуда не делась, ` +
                       `я по опыту знаю. ` : "";
      return `Месяц. ${z}Не покупай ничего, просто ответь себе: за этот месяц ` +
        `стало лучше или так же? Если так же — дело не в мотивации, а в том, ` +
        `что не на чем держаться.`;
    }
  }
  return null;
}

export const BTN_UNSUB = "Не писать больше";

/** У хвоста кнопки обязательны, у первых четырёх касаний их нет:
 *  там разговор ещё горячий и кнопка отписки подсказывает мысль уйти. */
export const warmupMarkup = (kind, contactCode) => {
  const item = SCHEDULE.find((s) => s.kind === kind);
  if (!item?.tail) return {};
  return {
    reply_markup: {
      inline_keyboard: [[
        { text: BTN_CONTACT, callback_data: "contact" },
        { text: BTN_UNSUB, callback_data: "unsub" },
      ]],
    },
  };
};

export const UNSUB_DONE = "Понял, больше не пишу. Если передумаешь — просто напиши сам.";

/** Ставит всю цепочку касаний от указанного момента.
 *
 * Живёт здесь, а не в кроне, чтобы crоn и launch не импортировали друг
 * друга по кругу: такие связи разваливаются не сразу, а в самый неудобный
 * момент, и отлаживаются мучительно.
 */
export async function scheduleWarmup(db, userId, fromISO) {
  const base = Date.parse(fromISO || new Date().toISOString());
  await db.batch(SCHEDULE.map((s) =>
    db.prepare(`INSERT INTO jobs (user_id, kind, due_at) VALUES (?1, ?2, ?3)`)
      .bind(userId, s.kind, new Date(base + s.after).toISOString())));
}
