def training_line(p) -> str:
    parts = [
        f"<b>Тренировки:</b> {p.trainings} раза в неделю, больше не нужно.",
    ]
    if p.knee:
        parts.append(
            "С коленями и голеностопом — программа в обход ударной нагрузки: "
            "никаких прыжков и бега на старте."
        )
    if p.back:
        parts.append(
            "Со спиной убираем осевую нагрузку и работаем над корпусом."
        )
    parts.append(
        "Четвёртая тренировка при твоём восстановлении будет отнимать "
        "результат, а не добавлять."
    )
    return " ".join(parts)


