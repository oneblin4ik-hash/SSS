def health_warning(p) -> str:
    """Обязателен, если в ответах есть heart или diab. Формулировка не меняется."""
    if not p.medic:
        return ""
    if "heart" in p.health and "diab" in p.health:
        what = "сердце и диабет"
    elif "heart" in p.health:
        what = "сердце или давление"
    else:
        what = "диабет"
    return (
        "<b>Отдельно и без обтекаемых формулировок.</b> Ты "
        f"{p.f('отметила', 'отметил')} {what}. Тренер здесь второй, а первый — "
        "врач: нужно разрешение на нагрузку и понимание, чего тебе нельзя. "
        "Это не отмена плана, а его порядок. Я работал с такими людьми и "
        "работаю, но начинаем с бумажки от доктора, а не с приседаний."
    )


