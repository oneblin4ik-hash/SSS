def training_line(p) -> str:
    """Повторяет строку про тренировки из блока 02 квиза."""
    tr = p.trainings
    mins = MINS_TXT.get(p.mins, "полчаса")
    parts = [
        f"<b>Тренировки:</b> {tr} {'раз' if tr == 1 else 'раза'} в неделю "
        f"по {mins} — ровно столько, сколько ты {p.f('назвала', 'назвал')}. "
        "План строится под это время, а не под идеальное.",
    ]
    if p.knee:
        parts.append(
            "С коленями и голеностопом — программа в обход ударной нагрузки: "
            "никаких прыжков и бега на старте."
        )
    if p.back:
        parts.append(
            "Со спиной убираем осевую нагрузку и работаем над корпусом."
        )
    parts.append(
        "И сразу предупрежу: на старте четвёртая тренировка чаще отнимает "
        "результат, чем добавляет — восстановление ещё не настроено. Начнём "
        "с трёх и добавим, когда тело будет готово."
        if p.trainings >= 4 else
        "Добавлять больше на старте не нужно: результат делает регулярность, "
        "а не объём."
    )
    return " ".join(parts)


