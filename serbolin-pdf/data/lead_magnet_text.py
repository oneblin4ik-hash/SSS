def task_text(p) -> str:
    """Задача по цели + предупреждение про неподвижную стрелку весов.

    Предупреждение обязательно там, где вес действительно может стоять:
    при рекомпозиции и при работе на силу. Это прямо оговорено и в спеке
    («Стрелка весов при этом может почти не двинуться»), и в микрофидбеке
    квиза на экране цели.
    """
    if p.goal == "mass":
        return (
            "Задача — набор массы. Еды понадобится больше, чем кажется: именно "
            "на этом спотыкаются чаще всего. Вес пойдёт вверх, и это план, "
            "а не ошибка."
        )
    if p.goal in ("tone", "power") or p.chart_mode == "form":
        return (
            "Задача не в жёстком похудении, а в аккуратной рекомпозиции: убрать "
            "мягкость, добавить плотность. <b>Стрелка весов при этом может "
            "почти не двинуться, а тело изменится.</b> Знай это заранее, иначе "
            "решишь, что метод не работает."
        )
    return (
        "Задача — похудение без откатов. Скорость тут не главное: вес "
        f"возвращается почти у всех, и разница между «{p.f('сбросила', 'сбросил')}» "
        f"и «{p.f('удержала', 'удержал')}» решается режимом, а не жёсткостью диеты."
    )


def first_changes(p) -> str:
    return p.f("талия, бёдра, руки", "живот, плечи, руки")


