#: Кадры, которых не хватило при последней сборке. Читает build_kurs.py.
MISSING: list[str] = []


def _frame(e: dict) -> str:
    """Кадр упражнения. Нет файла — пустое окно с подписью «кадр»: страница
    остаётся читаемой, и видно, чего ждём. У кардио кадра нет и не будет,
    там стоит пиктограмма."""
    src = e["frame"]
    if not src:
        return f'<div class="exf icon">{b.icon("flame", 40, g.GOLD_DEEP, 2)}</div>' 
    if src and (FRAMES / src).exists():
        return f'<div class="exf"><img src="{FRAME_SRC}/{src}" alt=""></div>'
    if src and src not in MISSING:
        MISSING.append(src)
    return '<div class="exf empty"><span>кадр</span></div>' 


def _card(code: str, reps: str) -> str:
    e = atlas.ex(code)
    hint = (f'<div class="exh">{e["short"]}</div>') if e["short"] else ""
    inner = (
        f'{_frame(e)}'
        f'<div class="ext">'
        f'<div class="exn">{e["name"]}</div>'
        f'<div class="exr">{reps}</div>'
        f'<div class="exe">{e["easy"]}</div>{hint}</div>')
    if e["video"]:
        return f'<a class="exc" href="{e["video"]}">{inner}</a>'
    return f'<div class="exc">{inner}</div>'


